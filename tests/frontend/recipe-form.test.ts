import { beforeEach, expect, it, vi } from 'vitest';
import { mount, flushPromises } from '@vue/test-utils';
import RecipeForm from '@/components/recipes/RecipeForm.vue';
import IngredientListEditor from '@/components/recipes/IngredientListEditor.vue';
import StepListEditor from '@/components/recipes/StepListEditor.vue';
import * as api from '@/api/client';
import { useRecipeStore } from '@/stores/recipes';
import { recipe, product, clone, page } from './helpers';
vi.mock('@/api/client');
const button = (w: any, text: string) => w.findAll('button').find((b: any) => b.text() === text)!;
const props = () => ({ recipe: null, categories: [{ id: 1, name: 'Food', color: null }], products: [product()], recipes: [recipe(2)] });
const global = { stubs: { PreferenceBadges: true, CostSummaryBlock: true, FlattenedProductList: true } };
beforeEach(() => { vi.resetAllMocks(); vi.mocked(api.fetchRecipeDependents).mockResolvedValue([]); });
it('product/subrecipe ingredients and steps survive form -> real store -> reopen', async () => {
    const store = useRecipeStore();
    let saved: any;
    vi.mocked(api.createRecipe).mockImplementation(async (body) => { saved = { ...clone(body), id: 7 }; return clone(saved); });
    vi.mocked(api.fetchRecipes).mockImplementation(async () => page([clone(saved)]));
    vi.mocked(api.fetchRecipeCategories).mockResolvedValue([]);
    const w = mount(RecipeForm, { props: props(), global });
    await w.get('input').setValue('Bread');
    await w.get('select').setValue('1');
    // Child editor public model events are the boundary to the parent form; editors are mounted, not mocked.
    w.getComponent(IngredientListEditor).vm.$emit('update:modelValue', [{ product_id: 1, sub_recipe_id: null, quantity_amount: 100, quantity_unit: 'g' }, { product_id: null, sub_recipe_id: 2, quantity_amount: 1, quantity_unit: 'serv' }]);
    w.getComponent(StepListEditor).vm.$emit('update:modelValue', [{ order: 0, description: 'Mix and bake' }]);
    await button(w, 'Создать').trigger('click');
    const [body] = w.emitted('save')![0]! as any;
    await store.create(body);
    await w.setProps({ recipe: store.allItems[0] as any });
    await flushPromises();
    expect((w.get('input').element as HTMLInputElement).value).toBe('Bread');
    expect(w.getComponent(IngredientListEditor).props('modelValue')).toEqual(body.ingredients.map(({ order, ...row }: any) => row));
    expect(w.getComponent(StepListEditor).props('modelValue')).toEqual([{ order: 0, description: 'Mix and bake' }]);
    await button(w, 'Сохранить').trigger('click');
    expect(w.emitted('save')![1]).toEqual([body, 7]);
});
it('pieces mode rejects invalid combination and returns to normal portions', async () => {
    const w = mount(RecipeForm, { props: props(), global });
    await w.get('input').setValue('Bread');
    await w.get('select').setValue('1');
    await w.get('[role=switch]').trigger('click');
    let numbers = w.findAll('input[type=number]');
    await numbers[0]!.setValue(2);
    await numbers[1]!.setValue(3);
    await button(w, 'Создать').trigger('click');
    expect(w.emitted('save')).toBeUndefined();
    await numbers[0]!.setValue(8);
    await numbers[1]!.setValue(2);
    await button(w, 'Создать').trigger('click');
    expect(w.emitted('save')![0]![0]).toMatchObject({ servings: 4, total_pieces: 8, pieces_per_portion: 2 });
    await w.get('[role=switch]').trigger('click');
    await button(w, 'Создать').trigger('click');
    expect(w.emitted('save')![1]![0]).toMatchObject({ servings: 4, total_pieces: null, pieces_per_portion: null });
});
it('real ingredient picker adds product and subrecipe; step editor accepts typed text', async () => {
    const w = mount(RecipeForm, { props: props(), global: { stubs: { ...global.stubs, teleport: true } } });
    await w.get('input').setValue('Dinner');
    await w.get('select').setValue('1');
    const editor = w.getComponent(IngredientListEditor);
    // Open the actual picker using its visible choose button.
    const choose = editor.findAll('button').find(b => b.text().includes('Выбрать'))!;
    await choose.trigger('click');
    await flushPromises();
    const options = w.findAll('[role=option]');
    expect(options.map(x => x.text())).toContain('Product 1');
    await options[0]!.trigger('click');
    await w.findAll('[role=tab]').find(x => x.text() === 'Рецепты')!.trigger('click');
    await w.get('[role=option]').trigger('click');
    await button(w, 'Готово').trigger('click');
    const steps = w.getComponent(StepListEditor);
    await steps.get('input[placeholder="Описание шага..."]').setValue('Bake');
    await button(steps, '+ Добавить').trigger('click');
    await button(w, 'Создать').trigger('click');
    expect(w.emitted('save')?.[0]?.[0]).toMatchObject({ ingredients: [expect.objectContaining({ product_id: 1, sub_recipe_id: null }), expect.objectContaining({ product_id: null, sub_recipe_id: 2 })], steps: [{ order: 1, description: 'Bake' }] });
});
it('failed save through real form and store keeps user-entered values visible', async () => {
    const { defineComponent, h } = await import('vue');
    const { useCrudView } = await import('@/composables/useCrudView');
    const { useToastStore } = await import('@/stores/toast');
    vi.mocked(api.createRecipe).mockRejectedValue({ response: { data: { detail: 'Cannot save' } } });
    const Host = defineComponent({ setup() { const view = useCrudView(useRecipeStore()); view.openNew(); return () => view.formOpen.value ? h(RecipeForm, { ...props(), onSave: view.onSave }) : h('p', 'Closed'); } });
    const w = mount(Host, { global });
    await w.get('input').setValue('Unsaved dinner');
    await w.get('select').setValue('1');
    await button(w, 'Создать').trigger('click');
    await flushPromises();
    expect((w.get('input').element as HTMLInputElement).value).toBe('Unsaved dinner');
    expect(w.text()).not.toContain('Closed');
    expect(useToastStore().toasts.at(-1)).toMatchObject({ message: 'Cannot save', type: 'error' });
});
